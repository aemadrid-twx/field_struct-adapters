# frozen_string_literal: true

module FieldStruct
  module Protobuf
    # Writes a +FileDescriptorProto+ from {DescriptorBuilder} as +.proto+
    # source, for teams that generate their own code with protoc.
    #
    # @api private
    class Printer
      # @return [Hash{Symbol=>String}]
      SCALARS = {TYPE_STRING: 'string', TYPE_BYTES: 'bytes', TYPE_BOOL: 'bool',
                 TYPE_INT64: 'int64', TYPE_DOUBLE: 'double'}.freeze

      # @param file [Object] a +Google::Protobuf::FileDescriptorProto+
      # @param klass [Class<FieldStruct::Base>]
      def initialize(file, klass)
        @file = file
        @klass = klass
      end

      # @return [String]
      def to_s
        lines = ["// #{@file.name}: generated by field_struct-protobuf from #{@klass.name}.",
                 '// Field numbers come from each field\'s proto: {number:} option.',
                 '', 'syntax = "proto3";', '']
        lines.push("package #{@file.package};", '') unless @file.package.empty?
        @file.dependency.each { |import| lines << %(import "#{import}";) }
        lines << '' unless @file.dependency.empty?
        @file.message_type.each { |message| lines.concat(message_lines(message)) }
        "#{lines.join("\n")}\n"
      end

      private

      # @param message [Object] a +Google::Protobuf::DescriptorProto+
      # @return [Array<String>]
      def message_lines(message)
        ["message #{message.name} {", *message.field.map { |field| "  #{field_line(field)}" }, '}']
      end

      # @param field [Object] a +Google::Protobuf::FieldDescriptorProto+
      # @return [String]
      def field_line(field)
        label = if field.label == :LABEL_REPEATED then 'repeated '
                elsif field.proto3_optional then 'optional '
                else ''
                end
        type = field.type == :TYPE_MESSAGE ? field.type_name : SCALARS.fetch(field.type)
        "#{label}#{type} #{field.name} = #{field.number};"
      end
    end
  end
end
