# frozen_string_literal: true

require 'open3'
require 'tmpdir'

RSpec.describe FieldStruct::Protobuf do
  let(:invoice) do
    PbSpec::Billing::Invoice.new(
      id: '0b9d6a4e-3c1f-4a59-9d1e-2f6a8c7b5e10', total: '19.90', at: '2026-10-27 09:30:00.123456789',
      status: :paid, tags: %w[rush gift], count: 3, paid: true, ship_to: {city: 'Provo', zip: '84601'},
      meta: {'source' => 'web', 'ids' => [1, 2]}, due_on: '2026-11-01', blob: "\xFF\x00".b, ratio: 0.25,
      homes: [{city: 'Orem'}], previous: {id: '1b9d6a4e-3c1f-4a59-9d1e-2f6a8c7b5e10', total: '1', at: '2026-01-01', status: :open,
                                          tags: [], homes: []}
    )
  end
  let(:minimal) do
    PbSpec::Billing::Invoice.new(id: '0b9d6a4e-3c1f-4a59-9d1e-2f6a8c7b5e10', total: '0', at: '2026-10-27', status: :open)
  end

  def round_trip(struct)
    described_class.decode(struct.class, described_class.encode(struct))
  end

  describe '.proto' do
    it 'writes the file for a class' do
      expect(described_class.proto(PbSpec::Billing::Address)).to eq(<<~PROTO)
        // field_struct/pb_spec/billing/address.proto: generated by field_struct-protobuf from PbSpec::Billing::Address.
        // Field numbers come from each field's proto: {number:} option.

        syntax = "proto3";

        package pb_spec.billing;

        message Address {
          optional string city = 1;
          optional string zip = 2;
        }
      PROTO
    end

    it 'imports the structs and well-known types it uses, and refers to itself without importing itself' do
      text = described_class.proto(PbSpec::Billing::Invoice)

      expect(text.scan(/^import "(.+)";$/).flatten)
        .to eq(%w[google/protobuf/timestamp.proto field_struct/pb_spec/billing/address.proto google/protobuf/struct.proto])
      expect(text).to include('  .pb_spec.billing.Invoice previous = 14;', '  repeated .pb_spec.billing.Address homes = 13;')
    end

    it 'compiles with protoc to the descriptor the gem registers' do
      ours = [PbSpec::Billing::Address, PbSpec::Billing::Invoice].map { |klass| described_class.file_descriptor(klass) }
      theirs = protoc(PbSpec::Billing::Address, PbSpec::Billing::Invoice)

      ours.each do |file|
        compiled = theirs.fetch(file.name)
        expect(compiled.dependency.to_a).to eq(file.dependency.to_a)
        expect(shape(compiled)).to eq(shape(file))
      end
    end

    it 'names fields after the protobuf serialization' do
      expect(described_class.proto(PbSpec::Renamed)).to include('optional string orderId = 1;')
    end

    def shape(file)
      file.message_type.map do |message|
        [message.name, message.oneof_decl.map(&:name),
         message.field.map { |f| [f.name, f.number, f.label, f.type, f.type_name, f.proto3_optional, f.oneof_index] }]
      end
    end

    # Writes each class's .proto under a temp dir and compiles them together.
    def protoc(*classes)
      Dir.mktmpdir do |dir|
        classes.each do |klass|
          path = File.join(dir, described_class.file_name(klass))
          FileUtils.mkdir_p(File.dirname(path))
          File.write(path, described_class.proto(klass))
        end
        out = File.join(dir, 'set.pb')
        files = classes.map { |klass| described_class.file_name(klass) }
        _, err, status = Open3.capture3(Gem.bin_path('grpc-tools', 'grpc_tools_ruby_protoc'), "-I#{dir}",
          "--descriptor_set_out=#{out}", *files, chdir: dir)
        raise "protoc failed: #{err}" unless status.success?

        Google::Protobuf::FileDescriptorSet.decode(File.binread(out)).file.to_h { |file| [file.name, file] }
      end
    end
  end

  describe '.encode / .decode' do
    it 'round-trips every mapped type' do
      expect(round_trip(invoice)).to eq(invoice)
    end

    it "keeps nanoseconds and restores the field's zone offset" do
      at = round_trip(invoice).at

      expect([at.nsec, at.utc_offset]).to eq([123_456_789, -6 * 3600])
    end

    it 'tells unset fields from zero, false and empty' do
      zeroes = PbSpec::Billing::Invoice.new(minimal.to_h.merge(count: 0, paid: false, ratio: 0.0, blob: ''.b))

      expect(round_trip(minimal).to_h.values_at(:count, :paid, :ratio, :blob, :ship_to, :meta, :due_on)).to all(be_nil)
      expect(round_trip(zeroes).to_h.values_at(:count, :paid, :ratio, :blob)).to eq([0, false, 0.0, ''.b])
    end

    it 'reads an unset repeated field back as an empty array, not nil' do
      expect(round_trip(minimal).tags).to eq([])
    end

    it 'reads JSON numbers in a :value back as floats' do
      expect(round_trip(invoice).meta).to eq('source' => 'web', 'ids' => [1.0, 2.0])
    end

    it 'gives the same bytes protoc-generated code would read' do
      message = described_class.message_class(PbSpec::Billing::Address).decode(described_class.encode(invoice.ship_to))

      expect([message.city, message.zip]).to eq(%w[Provo 84601])
    end

    it 'refuses nil inside a repeated field' do
      with_nil = PbSpec::Billing::Invoice.new(minimal.to_h.merge(tags: ['a', nil]))

      expect { described_class.encode(with_nil) }.to raise_error(ArgumentError, /repeated fields can't hold nil/)
    end

    it 'refuses a :value that is not JSON' do
      odd = PbSpec::Billing::Invoice.new(minimal.to_h.merge(meta: BigDecimal('1.5')))

      expect { described_class.encode(odd) }.to raise_error(ArgumentError, /holds JSON values.*BigDecimal/)
    end
  end

  describe 'what it refuses to guess' do
    it 'needs a number on every field' do
      expect { described_class.proto(PbSpec::Unnumbered) }.to raise_error(ArgumentError, /missing on b/)
    end

    it 'refuses a number used twice' do
      expect { described_class.proto(PbSpec::Twice) }.to raise_error(ArgumentError, /field numbers 1 are used twice/)
    end

    it "refuses protobuf's reserved numbers" do
      expect { described_class.proto(PbSpec::Reserved) }.to raise_error(ArgumentError, /19500 isn't a usable/)
    end

    it 'refuses unions, for now' do
      expect { described_class.proto(PbSpec::WithUnion) }.to raise_error(ArgumentError, /is a union/)
    end

    it 'refuses a name protobuf can not use' do
      expect { described_class.proto(PbSpec::BadName) }.to raise_error(ArgumentError, /"a-b" isn't a protobuf field name/)
    end

    it 'refuses an anonymous class' do
      expect { described_class.proto(Class.new(FieldStruct::Base)) }.to raise_error(ArgumentError, /named class/)
    end

    it 'refuses structs that refer to each other, which would be files importing each other' do
      expect { described_class.message_class(PbSpec::Ping) }
        .to raise_error(ArgumentError, /PbSpec::Ping -> PbSpec::Pong -> PbSpec::Ping/)
    end
  end
end
